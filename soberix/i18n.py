# Resolvido uma vez por processo (simples e suficiente para o app)
_LANG: str | None = None


def _detect_lang() -> str:
    saved = settings.load().get("language", "auto")
    if saved in SUPPORTED:
        return saved
    env = (os.environ.get("LC_ALL") or os.environ.get("LC_MESSAGES")
           or os.environ.get("LANG") or "en")
    prefix = env.lower().split(".")[0][:2]
    if prefix == "pt":
        return "pt"
    return prefix if prefix in SUPPORTED else "en"


def lang() -> str:
    global _LANG
    if _LANG is None:
        _LANG = _detect_lang()
    return _LANG


def set_lang(value: str) -> None:
    """Define o idioma em tempo de execução ('auto' | código de 2 letras).

    Usado pela GUI para trocar o idioma sem reiniciar o app.
    """
    global _LANG
    if value == "auto":
        _LANG = None  # re-detecta pelo ambiente
        _LANG = _detect_lang()
    else:
        _LANG = value if value in SUPPORTED else "en"


def t(key: str, **fmt) -> str:
    """Texto no idioma ativo; cai para en, depois pt, depois a própria chave."""
    text = (STRINGS.get(lang(), {}).get(key)
            or STRINGS["en"].get(key)
            or STRINGS["pt"].get(key)
            or key)
    return text.format(**fmt) if fmt else text
